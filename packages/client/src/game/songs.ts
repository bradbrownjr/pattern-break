// The songs bundled with the client. M1 has one: the test module (a song file made in a
// music tracker) that tools/make-fixture-mod.ts generates. M4 replaces this list with the
// music pack and music/manifest.json.

import fixtureUrl from '@game/analysis/fixtures/pb-fixture-01.mod?url';

export interface BundledSong {
  /** The id capture mode's `song` parameter names. */
  id: string;
  url: string;
  /** The title as the file writes it. */
  title: string;
  /** Who made it and the license, as shown on the title screen. */
  credit: string;
}

export const SONGS: readonly BundledSong[] = [
  {
    id: 'pb-fixture-01',
    url: fixtureUrl,
    title: 'pb fixture 01',
    credit: 'Generated by this repository. MIT license.',
  },
];

export function findSong(id: string | null): BundledSong | null {
  if (id === null) return SONGS[0] ?? null;
  return SONGS.find((s) => s.id === id) ?? null;
}

export async function fetchSongBytes(song: BundledSong): Promise<Uint8Array> {
  const response = await fetch(song.url);
  if (!response.ok) throw new Error(`Could not load ${song.title} (${response.status})`);
  return new Uint8Array(await response.arrayBuffer());
}
