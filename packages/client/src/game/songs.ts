// The songs bundled with the client (song files made in a music tracker), in the order of
// music/manifest.json, which holds their credits and licenses (docs/PLAN.md, "Bundled
// music"), and the part each plays in the game. The generated test song is not offered to
// players; capture mode and the screenshots can still name it.

import testSongUrl from '@game/analysis/fixtures/pb-fixture-01.mod?url';
import arcade from '../../../../music/arcade.json';
import manifest from '../../../../music/manifest.json';
import type { StoredSong } from './library.ts';

export interface BundledSong {
  /** The file name without its extension: what capture mode's and the page's `song` parameter name. */
  id: string;
  url: string;
  title: string;
  author: string;
  license: string;
  /**
   * Who made it, as one line for the screen ("by Drozerix"). The license is on the Credits
   * screen, not here (Brad, 2026-11-10: on every song line it was redundant).
   */
  credit: string;
  /** The song's page where it was published (The Mod Archive), or null. */
  sourceUrl: string | null;
  /** SHA-256 of the file from the manifest (checked by tools/validate-manifest.ts), naming it in replays; null for the test song. */
  sha256: string | null;
  /** Imported by the player (library.ts) rather than bundled; `url` is then an object URL. */
  imported: boolean;
}

const urls = import.meta.glob<string>('../../../../music/*.{mod,xm,s3m,it,mptm}', {
  query: '?url',
  import: 'default',
  eager: true,
});

export const SONGS: readonly BundledSong[] = manifest.map((entry) => {
  const url = urls[`../../../../music/${entry.file}`];
  if (!url) throw new Error(`music/${entry.file} is in the manifest but was not bundled`);
  return {
    id: entry.file.replace(/\.[^.]+$/, ''),
    url,
    title: entry.title,
    author: entry.author,
    license: entry.license,
    credit: `by ${entry.author}`,
    sourceUrl: entry.sourceUrl,
    sha256: entry.sha256,
    imported: false,
  };
});

