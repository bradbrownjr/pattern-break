/**
 * Whether the browser's file picker can pick a folder (`webkitdirectory`, from the WICG
 * File and Directory Entries API; Baseline since August 2025 per MDN).
 */
export const FOLDER_PICKER = typeof HTMLInputElement !== 'undefined' && 'webkitdirectory' in HTMLInputElement.prototype;

/** The file types the game imports: tracker formats only (docs/PLAN.md, "Hard rules"). */
export const IMPORT_EXTENSIONS: readonly string[] = ['.mod', '.xm', '.s3m', '.it'];

/** True for a file name the game imports, by its extension, in any case. */
export function isSongFileName(name: string): boolean {
  const lower = name.toLowerCase();
  return IMPORT_EXTENSIONS.some((ext) => lower.endsWith(ext));
}

/** A file name without its folder or extension, as a title for a song that has none. */
export function titleFromFileName(name: string): string {
  const base = name.slice(name.lastIndexOf('/') + 1);
  const dot = base.lastIndexOf('.');
  return dot > 0 ? base.slice(0, dot) : base;
}

/**
 * The song entry for an imported file: its id comes from the hash, so personal bests stay
 * with the song, and `url` is an object URL for its bytes (revoke it when the song goes).
 */
export function importedSong(stored: StoredSong): BundledSong {
  return {
    id: `imported-${stored.sha256.slice(0, 12)}`,
    url: URL.createObjectURL(new Blob([stored.bytes])),
    title: stored.title,
    author: stored.artist,
    license: 'Imported',
    credit: stored.artist ? `by ${stored.artist}. Imported.` : 'Imported.',
    sourceUrl: null,
    sha256: stored.sha256,
    imported: true,
  };
}

/** The bundled song whose file has this SHA-256, or null. */
export function songBySha256(hash: string): BundledSong | null {
  return SONGS.find((s) => s.sha256 === hash) ?? null;
}

/** The song with this id, the first bundled song for null, or null for an unknown id. */
export function findSong(id: string | null): BundledSong | null {
  if (id === null) return SONGS[0] ?? null;
  if (id === TEST_SONG.id) return TEST_SONG;
  return SONGS.find((s) => s.id === id) ?? null;
}

export async function fetchSongBytes(song: BundledSong): Promise<Uint8Array> {
  const response = await fetch(song.url);
  if (!response.ok) throw new Error(`Could not load ${song.title} (${response.status})`);
  return new Uint8Array(await response.arrayBuffer());
}
