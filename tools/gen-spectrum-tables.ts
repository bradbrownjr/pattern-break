// Generates packages/core/src/spectrum/tables.generated.ts: FFT twiddles, the Hann window,
// band bin ranges, and LED power thresholds. Core may not call transcendental Math at
// runtime, so these values are computed here and committed as number literals.
//
// Run: pnpm gen:tables
// packages/core/test/spectrum-tables.test.ts fails if the committed file is out of date.

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import {
  BAND_COUNT,
  BAND_HIGH_HZ,
  BAND_LOW_HZ,
  FFT_SIZE,
  LED_BOTTOM_DB,
  LED_LEVELS,
  LED_STEP_DB,
  SAMPLE_RATE,
} from '../packages/core/src/analysis-constants.ts';

export const TABLES_PATH = fileURLToPath(
  new URL('../packages/core/src/spectrum/tables.generated.ts', import.meta.url),
);

const HALF = FFT_SIZE / 2;
const BIN_HZ = SAMPLE_RATE / FFT_SIZE;

function twiddles(): { cos: number[]; sin: number[] } {
  const cos: number[] = [];
  const sin: number[] = [];
  for (let k = 0; k < HALF; k++) {
    const a = (2 * Math.PI * k) / FFT_SIZE;
    cos.push(Math.cos(a));
    sin.push(Math.sin(a));
  }
  return { cos, sin };
}

/** Periodic Hann window: w[n] = 0.5 - 0.5 cos(2 pi n / N). */
function hann(): number[] {
  const w: number[] = [];
  for (let n = 0; n < FFT_SIZE; n++) w.push(0.5 - 0.5 * Math.cos((2 * Math.PI * n) / FFT_SIZE));
  return w;
}

function bandEdgeHz(edge: number): number {
  return BAND_LOW_HZ * Math.pow(BAND_HIGH_HZ / BAND_LOW_HZ, edge / BAND_COUNT);
}

/**
 * Band b covers bins [start, end): the bins whose centre frequency is in
 * [edge(b), edge(b + 1)). A band that would be empty gets one bin, and every band starts
 * where the previous one ended, so bands never overlap.
 */
function bandBins(): { start: number[]; end: number[] } {
  const start: number[] = [];
  const end: number[] = [];
  let prevEnd = 1; // bin 0 (DC) is never used
  for (let b = 0; b < BAND_COUNT; b++) {
    const s = Math.max(Math.ceil(bandEdgeHz(b) / BIN_HZ), prevEnd);
    const e = Math.max(Math.ceil(bandEdgeHz(b + 1) / BIN_HZ), s + 1);
    if (e > HALF) throw new Error(`band ${b} ends past Nyquist`);
    start.push(s);
    end.push(e);
    prevEnd = e;
  }
  return { start, end };
}

/**
 * Mean power, over the band's bins, of a windowed full-scale sine (amplitude 1, phase 0 at
 * the window's first sample) at the band's geometric centre frequency. Power is the raw
 * |X[k]|^2 of the windowed DFT, the same unscaled quantity the runtime computes.
 */
function referencePower(b: number, window: number[], start: number, end: number): number {
  const f = Math.sqrt(bandEdgeHz(b) * bandEdgeHz(b + 1));
  const x: number[] = [];
  for (let n = 0; n < FFT_SIZE; n++) x.push(Math.sin((2 * Math.PI * f * n) / SAMPLE_RATE) * window[n]!);
  let sum = 0;
  for (let k = start; k < end; k++) {
    let re = 0;
    let im = 0;
    for (let n = 0; n < FFT_SIZE; n++) {
      const a = (2 * Math.PI * ((k * n) % FFT_SIZE)) / FFT_SIZE;
      re += x[n]! * Math.cos(a);
      im -= x[n]! * Math.sin(a);
    }
    sum += re * re + im * im;
  }
  return sum / (end - start);
}

function literalList(values: readonly number[], perLine: number): string {
  const lines: string[] = [];
  for (let i = 0; i < values.length; i += perLine) {
    lines.push(`  ${values.slice(i, i + perLine).map((v) => v.toString()).join(', ')},`);
  }
  return lines.join('\n');
}

export function generateSpectrumTables(): string {
  const { cos, sin } = twiddles();
  const window = hann();
  const bins = bandBins();
  const thresholds: number[] = [];
  for (let b = 0; b < BAND_COUNT; b++) {
    const ref = referencePower(b, window, bins.start[b]!, bins.end[b]!);
    for (let i = 0; i < LED_LEVELS; i++) {
      thresholds.push(ref * Math.pow(10, (LED_BOTTOM_DB + LED_STEP_DB * i) / 10));
    }
  }

  return `// Generated by tools/gen-spectrum-tables.ts. Do not edit; run \`pnpm gen:tables\`.
// FFT_SIZE ${FFT_SIZE}, SAMPLE_RATE ${SAMPLE_RATE}, BAND_COUNT ${BAND_COUNT} (${BAND_LOW_HZ} to ${BAND_HIGH_HZ} Hz),
// LED_LEVELS ${LED_LEVELS} (${LED_BOTTOM_DB} dB in ${LED_STEP_DB} dB steps).

/** cos(2 pi k / FFT_SIZE) for k in 0..FFT_SIZE/2-1. */
export const TWIDDLE_COS = new Float64Array([
${literalList(cos, 4)}
]);

/** sin(2 pi k / FFT_SIZE) for k in 0..FFT_SIZE/2-1. */
export const TWIDDLE_SIN = new Float64Array([
${literalList(sin, 4)}
]);

/** Periodic Hann window of length FFT_SIZE. */
export const HANN_WINDOW = new Float64Array([
${literalList(window, 4)}
]);

/** First FFT bin of each band. */
export const BAND_BIN_START = new Uint16Array([
${literalList(bins.start, 16)}
]);

/** One past the last FFT bin of each band. */
export const BAND_BIN_END = new Uint16Array([
${literalList(bins.end, 16)}
]);

/**
 * LED thresholds on mean raw bin power, BAND_COUNT rows of LED_LEVELS, ascending. Row b
 * is the reference power of band b (a full-scale sine at the band's centre) times
 * 10^(dB / 10) for dB = ${LED_BOTTOM_DB}, ${LED_BOTTOM_DB + LED_STEP_DB}, ..., ${LED_BOTTOM_DB + LED_STEP_DB * (LED_LEVELS - 1)}.
 */
export const LED_THRESHOLDS = new Float64Array([
${literalList(thresholds, 4)}
]);
`;
}

if (import.meta.main) {
  writeFileSync(TABLES_PATH, generateSpectrumTables());
  console.log(`wrote ${TABLES_PATH}`);
}
